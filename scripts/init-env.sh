#!/usr/bin/env bash
# ==============================================================================
# init-env.sh - create .env and fill in the secrets the enabled services need
# ==============================================================================
# Fresh installation helper. It:
#   1. copies .env.example to .env if .env does not exist yet (mode 600)
#   2. generates a random value for every secret that is still empty
#
# It never overwrites a value you already set, so it is safe to re-run after
# adding a profile.
#
# Usage:
#   scripts/init-env.sh
#   scripts/init-env.sh --force-secrets    also replace existing secrets
# ==============================================================================
set -euo pipefail
umask 077

SCRIPT_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
ROOT=$(dirname -- "$SCRIPT_DIR")
. "$SCRIPT_DIR/lib-env.sh"

ENV_FILE=${AINODE_ENV_FILE:-$ROOT/.env}
EXAMPLE=$ROOT/.env.example
FORCE=0
case ${1:-} in
    --force-secrets) FORCE=1 ;;
    -h|--help) sed -n '2,16p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
    "") ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
esac

ainode_require_cmd openssl "secrets are generated with it" "pacman -S openssl" || exit 1

created=0
if [ ! -f "$ENV_FILE" ]; then
    [ -f "$EXAMPLE" ] || { echo "error: no $EXAMPLE to copy" >&2; exit 1; }
    cp "$EXAMPLE" "$ENV_FILE"
    created=1
fi
chmod 600 "$ENV_FILE"

# Secrets that the default profiles cannot work without. WEBUI_SECRET_KEY is
# deliberately not here: empty means Open WebUI manages its own key.
SECRETS="CRAWL4AI_API_TOKEN SEARXNG_SECRET"

tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT
generated=""
: > "$tmp"

while IFS= read -r line || [ -n "$line" ]; do
    replaced=0
    for key in $SECRETS; do
        case $line in
            "$key=")
                printf '%s=%s\n' "$key" "$(openssl rand -hex 24)" >> "$tmp"
                generated="$generated $key"
                replaced=1
                ;;
            "$key="*)
                if [ "$FORCE" = 1 ]; then
                    printf '%s=%s\n' "$key" "$(openssl rand -hex 24)" >> "$tmp"
                    generated="$generated $key"
                    replaced=1
                fi
                ;;
        esac
        [ "$replaced" = 0 ] || break
    done
    [ "$replaced" = 1 ] || printf '%s\n' "$line" >> "$tmp"
done < "$ENV_FILE"

# Keys that are missing from the file entirely (an older .env)
for key in $SECRETS; do
    if ! grep -q "^$key=" "$tmp"; then
        printf '\n# generated by scripts/init-env.sh\n%s=%s\n' "$key" "$(openssl rand -hex 24)" >> "$tmp"
        generated="$generated $key"
    fi
done

if cmp -s "$ENV_FILE" "$tmp"; then
    echo "env: nothing to do ($ENV_FILE already populated)" >&2
else
    cat "$tmp" > "$ENV_FILE"
    chmod 600 "$ENV_FILE"
    echo "env: wrote $ENV_FILE" >&2
fi

[ "$created" = 1 ] && echo "env: created from .env.example" >&2
[ -n "$generated" ] && echo "env: generated$generated" >&2
echo "env: next, set AINODE_USER_UID and the GPU group ids (see the comments in .env)" >&2
