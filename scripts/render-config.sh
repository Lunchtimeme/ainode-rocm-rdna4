#!/usr/bin/env bash
# ==============================================================================
# render-config.sh - generate nginx vhosts from examples/reverseproxy
# ==============================================================================
# The vhosts in data/reverseproxy/sites-enabled are generated: they carry the
# LAN domain, the container prefix and the two bearer tokens, none of which
# belong in a tracked nginx config. The versioned source of truth is
# examples/reverseproxy/. Edit those, run this, reload nginx.
#
# Why generate instead of mounting the templates: a vhost whose upstream does
# not exist must not be loaded at all. nginx with a literal `proxy_pass` to a
# missing container starts its master but spawns no worker, so EVERY vhost dies
# silently. Skipping the file (or, belt and braces, the `set $upstream` form in
# the templates) keeps the rest of the proxy serving.
#
# Usage:
#   scripts/render-config.sh              render into data/reverseproxy/sites-enabled
#   scripts/render-config.sh --check      render to a temp dir and diff, change nothing
#   scripts/render-config.sh --reload     render, then nginx -t and nginx -s reload
#
# Conditions are declared in the template's first lines:
#   # render-if: none                  always
#   # render-if: profile comfyui       only when comfyui is in COMPOSE_PROFILES
#   # render-if: var PRISM_ENABLE 1    only when $PRISM_ENABLE equals 1
#
# Templates are rendered with an explicit envsubst list, so nginx's own
# variables ($host, $remote_addr, $server_addr, ...) are left untouched.
# ==============================================================================
set -euo pipefail

SCRIPT_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
ROOT=$(dirname -- "$SCRIPT_DIR")
ENV_FILE=${AINODE_ENV_FILE:-$ROOT/.env}
TEMPLATE_DIR=${AINODE_TEMPLATE_DIR:-$ROOT/examples/reverseproxy}
OUT_DIR=${AINODE_VHOST_DIR:-$ROOT/data/reverseproxy/sites-enabled}
MARKER="Generated by scripts/render-config.sh"

MODE=render
for arg in "$@"; do
    case $arg in
        --check)  MODE=check ;;
        --reload) MODE=reload ;;
        -h|--help) sed -n '2,30p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *) echo "unknown argument: $arg" >&2; exit 2 ;;
    esac
done

[ -f "$TEMPLATE_DIR/00map" ] || { echo "no templates in $TEMPLATE_DIR" >&2; exit 1; }

# ------------------------------------------------------------------------------
# Load .env without eval: KEY=VALUE, optional surrounding quotes, no commands.
# ------------------------------------------------------------------------------
if [ -f "$ENV_FILE" ]; then
    set -a
    while IFS='=' read -r key val || [ -n "$key" ]; do
        case $key in ''|'#'*) continue ;; esac
        key=${key//[[:space:]]/}
        # Shell environment wins over .env, matching `docker compose` precedence
        # (otherwise `COMPOSE_PROFILES=x scripts/render-config.sh` would be
        # silently overridden by the file and nothing would be skipped).
        [ -n "${!key+x}" ] && continue
        case $val in
            \"*\") val=${val#\"}; val=${val%\"} ;;
            \'*\') val=${val#\'}; val=${val%\'} ;;
        esac
        export "$key=$val"
    done < "$ENV_FILE"
    set +a
else
    echo "warning: $ENV_FILE not found, using defaults" >&2
fi

PROFILES=",${COMPOSE_PROFILES:-},"
SUBST_VARS='${AINODE_PREFIX} ${AINODE_LAN_DOMAIN} ${CRAWL4AI_API_TOKEN} ${STRATA_API_KEY}'

export AINODE_PREFIX=${AINODE_PREFIX:-ainode}
export AINODE_LAN_DOMAIN=${AINODE_LAN_DOMAIN:-localdomain}

wanted=$(mktemp)
checkdir="./$(basename "$wanted").out"
trap 'rm -f "$wanted"; [ -d "$checkdir" ] && rm -f "$checkdir"/* && rmdir "$checkdir" 2>/dev/null; true' EXIT

should_render() {
    local file=$1 cond kind needle extra
    cond=$(sed -n '1,20s/^# render-if:[[:space:]]*//p' "$file" | head -1)
    cond=${cond:-none}
    read -r kind needle extra <<<"$cond"
    case $kind in
        none) return 0 ;;
        profile)
            case $PROFILES in *",$needle,"*) return 0 ;; esac
            echo "  skip $(basename "$file"): profile '$needle' not enabled" >&2
            return 1 ;;
        var)
            if [ "${!needle:-}" = "$extra" ]; then return 0; fi
            echo "  skip $(basename "$file"): $needle is not $extra" >&2
            return 1 ;;
        *)
            echo "  skip $(basename "$file"): unknown condition '$cond'" >&2
            return 1 ;;
    esac
}

render_one() {
    local src=$1 dst=$2 name
    name=$(basename "$src")
    # A token that is empty would render "Authorization: Bearer " and turn a
    # working vhost into a 401 farm; better to not publish it at all.
    case $name in
        40crawl4ai) [ -n "${CRAWL4AI_API_TOKEN:-}" ] || { echo "  skip $name: CRAWL4AI_API_TOKEN is empty" >&2; return 1; } ;;
        60strata)   [ -n "${STRATA_API_KEY:-}" ]     || { echo "  skip $name: STRATA_API_KEY is empty" >&2; return 1; } ;;
    esac
    local tmpout="$dst.new.$$"
    {
        echo "# $MARKER from examples/reverseproxy/$name"
        echo "# Edit the template, not this file."
        envsubst "$SUBST_VARS" < "$src"
    } > "$tmpout" || { echo "  FAILED $name: cannot write $tmpout" >&2; rm -f "$tmpout"; return 1; }
    mv -f "$tmpout" "$dst" || { echo "  FAILED $name: cannot replace $dst" >&2; rm -f "$tmpout"; return 1; }
    echo "  $name"
    echo "$name" >> "$wanted"
}

if [ "$MODE" = check ]; then
    mkdir -p "$checkdir"
    tmp=$checkdir
    echo "rendering to $tmp (check mode)" >&2
    for tpl in "$TEMPLATE_DIR"/*; do
        [ -f "$tpl" ] || continue
        should_render "$tpl" || continue
        render_one "$tpl" "$tmp/$(basename "$tpl")" || true
    done
    rc=0
    if diff -ru "$OUT_DIR" "$tmp" > /tmp/ainode-vhost-diff.$$ 2>&1; then
        echo "vhosts are up to date" >&2
    else
        echo "vhosts differ from templates:" >&2
        sed 's/^/  /' /tmp/ainode-vhost-diff.$$ >&2
        rc=1
    fi
    rm -f /tmp/ainode-vhost-diff.$$
    exit $rc
fi

mkdir -p "$OUT_DIR"
if [ ! -w "$OUT_DIR" ]; then
    cat >&2 <<EOF
error: $OUT_DIR is not writable by $(id -un).
       It is runtime config owned by root (created by an older install).
       Fix once with:
         sudo chown -R $(id -u):$(id -g) $(dirname "$OUT_DIR")
       nginx reads these files as root, so ownership does not affect serving.
EOF
    exit 1
fi
echo "rendering $TEMPLATE_DIR -> $OUT_DIR" >&2
for tpl in "$TEMPLATE_DIR"/*; do
    [ -f "$tpl" ] || continue
    should_render "$tpl" || continue
    render_one "$tpl" "$OUT_DIR/$(basename "$tpl")" || true
done

# Remove files this script generated earlier that no template produces anymore
# (a profile turned off, a template renamed). Hand-written files are left alone.
for existing in "$OUT_DIR"/*; do
    [ -f "$existing" ] || continue
    name=$(basename "$existing")
    grep -q "^# $MARKER" "$existing" || continue
    grep -qx "$name" "$wanted" && continue
    echo "  remove stale $name" >&2
    rm -f "$existing"
done

if [ "$MODE" = reload ]; then
    container="${AINODE_PREFIX}-reverseproxy"
    echo "testing and reloading $container" >&2
    docker exec "$container" nginx -t
    docker exec "$container" nginx -s reload
fi

echo "done" >&2
